export function translateZhCN(value: string): string {
  if (!/[A-Za-z]/.test(value)) return value;
  // Explicit UI messages only. Never apply substring replacement to data.
  for (const [pattern, replacement] of replacements) {
    const exact = new RegExp(`^(?:${pattern.source})$`, 'i');
    if (exact.test(value)) return value.replace(exact, replacement);
  }
  return value;
}

